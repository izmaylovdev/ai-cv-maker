"""Guards the protobuf runtime floor against the checked-in gRPC gencode.

``app/grpc/llm_service_pb2.py`` is generated by protoc and committed. Its
``# Protobuf Python Version: X`` stamp is the gencode version, and the protobuf
Python runtime refuses to load gencode that is newer than itself or from a
different major version. When ``pyproject.toml`` let a stale venv keep an older
protobuf, llm-service crashed at import with a ``VersionError`` and every AI
feature returned 503. These tests fail the suite instead:

* the requirement in ``pyproject.toml`` must pin protobuf to the stamp's major
  with a floor at or above the stamp, so ``llm-service:install`` upgrades an
  old venv; and
* the generated module must actually import with the installed runtime, which
  is the same check ``serve`` would otherwise fail on.
"""

from __future__ import annotations

import importlib
import re
import tomllib
from pathlib import Path

SERVICE_ROOT = Path(__file__).resolve().parent.parent
PYPROJECT = SERVICE_ROOT / "pyproject.toml"
GENCODE = SERVICE_ROOT / "app" / "grpc" / "llm_service_pb2.py"

_STAMP_RE = re.compile(r"^#\s*Protobuf Python Version:\s*(\d+(?:\.\d+)*)\s*$", re.MULTILINE)
_NAME_RE = re.compile(r"^\s*([A-Za-z0-9][A-Za-z0-9._-]*)")
_SPEC_RE = re.compile(r"(>=|<=|==|!=|~=|>|<)\s*(\d+(?:\.\d+)*)")


def _version_tuple(version: str) -> tuple[int, ...]:
    return tuple(int(part) for part in version.split("."))


def _padded(version: tuple[int, ...], width: int = 3) -> tuple[int, ...]:
    return version + (0,) * (width - len(version))


def _gencode_stamp() -> str:
    match = _STAMP_RE.search(GENCODE.read_text(encoding="utf-8"))
    assert match, (
        f"No '# Protobuf Python Version: X' stamp found in {GENCODE}; "
        "the protobuf floor guard cannot verify the gencode version"
    )
    return match.group(1)


def _protobuf_requirement() -> str | None:
    with PYPROJECT.open("rb") as fh:
        dependencies = tomllib.load(fh)["project"]["dependencies"]
    for requirement in dependencies:
        name_match = _NAME_RE.match(requirement)
        if not name_match:
            continue
        name = re.sub(r"[-_.]+", "-", name_match.group(1)).lower()
        if name == "protobuf":
            return requirement
    return None


def test_protobuf_floor_covers_checked_in_gencode() -> None:
    stamp = _gencode_stamp()
    stamp_tuple = _padded(_version_tuple(stamp))
    next_major = stamp_tuple[0] + 1

    requirement = _protobuf_requirement()
    assert requirement is not None, (
        f"gencode {GENCODE.name} is stamped protobuf {stamp}, but {PYPROJECT.name} "
        f"[project].dependencies has no 'protobuf' requirement; "
        f"expected something like 'protobuf>={stamp},<{next_major}'"
    )

    specifiers = _SPEC_RE.findall(requirement)
    floors = [_padded(_version_tuple(v)) for op, v in specifiers if op == ">="]
    uppers = [_padded(_version_tuple(v)) for op, v in specifiers if op == "<"]

    assert floors, (
        f"gencode stamp is protobuf {stamp}, but pyproject requirement "
        f"'{requirement}' has no '>=' floor"
    )
    floor = max(floors)
    assert floor >= stamp_tuple, (
        f"gencode stamp is protobuf {stamp}, but pyproject requirement "
        f"'{requirement}' allows an older runtime; raise the floor to >={stamp}"
    )

    assert uppers, (
        f"gencode stamp is protobuf {stamp}, but pyproject requirement "
        f"'{requirement}' has no '<' upper bound; add <{next_major} so a "
        "different major runtime cannot be installed"
    )
    upper = min(uppers)
    assert upper <= _padded((next_major,)), (
        f"gencode stamp is protobuf {stamp}, but pyproject requirement "
        f"'{requirement}' admits a different major runtime; cap it at <{next_major}"
    )
    assert upper > floor, (
        f"gencode stamp is protobuf {stamp}, but pyproject requirement "
        f"'{requirement}' has an empty range"
    )


def test_generated_stubs_load_with_installed_runtime() -> None:
    # Imported inside the test so a VersionError fails only this test and the
    # floor guard above still gets collected and runs.
    module = importlib.import_module("app.grpc.llm_service_pb2")
    assert module.DESCRIPTOR.name == "llm_service.proto"
